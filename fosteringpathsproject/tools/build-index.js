#!/usr/bin/env node
// Regenerates data/states/index.js (the manifest the browser uses to lazy-load
// a state's data files) from whatever files exist on disk.
// Usage: node tools/build-index.js
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.resolve(__dirname, "..");
const STATES_DIR = path.join(ROOT, "data", "states");
const NAMES = {AL:"Alabama",AK:"Alaska",AZ:"Arizona",AR:"Arkansas",CA:"California",CO:"Colorado",CT:"Connecticut",DE:"Delaware",DC:"District of Columbia",FL:"Florida",GA:"Georgia",HI:"Hawaii",ID:"Idaho",IL:"Illinois",IN:"Indiana",IA:"Iowa",KS:"Kansas",KY:"Kentucky",LA:"Louisiana",ME:"Maine",MD:"Maryland",MA:"Massachusetts",MI:"Michigan",MN:"Minnesota",MS:"Mississippi",MO:"Missouri",MT:"Montana",NE:"Nebraska",NV:"Nevada",NH:"New Hampshire",NJ:"New Jersey",NM:"New Mexico",NY:"New York",NC:"North Carolina",ND:"North Dakota",OH:"Ohio",OK:"Oklahoma",OR:"Oregon",PA:"Pennsylvania",RI:"Rhode Island",SC:"South Carolina",SD:"South Dakota",TN:"Tennessee",TX:"Texas",UT:"Utah",VT:"Vermont",VA:"Virginia",WA:"Washington",WV:"West Virginia",WI:"Wisconsin",WY:"Wyoming"};

// Order matters only in that guide/scholarships/resources are small and programs are big.
const ORDER = ["guide", "scholarships", "resources", "apprenticeships", "wages", "programs"];
const rank = (f) => { const i = ORDER.findIndex(k => f.startsWith(k)); return i === -1 ? 99 : i; };

const countFile = (file) => {
  const c = { programs: 0, resources: 0, scholarships: 0, guide: 0, apprenticeships: 0, wages: 0, regions: {} };
  const bump = (p) => { if (p && p.region) c.regions[p.region] = (c.regions[p.region] || 0) + 1; };
  const win = {
    registerResources: (a) => { c.resources += a.length; a.forEach(bump); },
    registerResource: (r) => { c.resources++; bump(r); },
    registerScholarships: (a) => { c.scholarships += a.length; },
    registerStateGuide: () => { c.guide++; },
    registerPrograms: (o) => { const v = Object.values(o); c.programs += v.length; v.forEach(bump); },
    registerProgram: (p) => { c.programs++; bump(p); },
    registerApprenticeships: (a) => { c.apprenticeships += a.length; },
    registerApprenticeship: () => { c.apprenticeships++; },
    registerWages: (o) => { c.wages += Object.keys(o.careers || o).length; },
  };
  const ctx = { window: win, console }; ctx.globalThis = ctx;
  vm.runInNewContext(fs.readFileSync(file, "utf8"), ctx, { filename: file, timeout: 20000 });
  return c;
};

const index = {};
for (const st of fs.readdirSync(STATES_DIR).sort()) {
  const dir = path.join(STATES_DIR, st);
  if (!fs.statSync(dir).isDirectory() || !NAMES[st]) continue;
  const files = fs.readdirSync(dir).filter(f => f.endsWith(".js")).sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));
  const counts = { programs: 0, resources: 0, scholarships: 0, guide: false, apprenticeships: 0, wages: 0 };
  const regions = {};
  let bytes = 0;
  for (const f of files) {
    const full = path.join(dir, f);
    bytes += fs.statSync(full).size;
    try {
      const c = countFile(full);
      counts.programs += c.programs; counts.resources += c.resources; counts.scholarships += c.scholarships;
      counts.apprenticeships += c.apprenticeships; counts.wages += c.wages;
      if (c.guide) counts.guide = true;
      for (const [r, n] of Object.entries(c.regions)) regions[r] = (regions[r] || 0) + n;
    } catch (e) {
      console.error(`skipping ${st}/${f}: ${e.message}`);
      files.splice(files.indexOf(f), 1);
    }
  }
  if (st === "CA") {
    // Legacy curated CA data: programs.js loads on every page (careers reference it);
    // apprenticeships.js (CA DAS, 750 KB) is lazy-loaded with the CA bundle.
    for (const f of ["programs.js", "apprenticeships.js"]) {
      try { const c = countFile(path.join(ROOT, "data", f)); counts.programs += c.programs; counts.apprenticeships += c.apprenticeships; } catch (e) {}
    }
    files.unshift("../../apprenticeships.js");
  }
  const regionList = Object.entries(regions).sort((a, b) => b[1] - a[1]).map(([r]) => r);
  index[st] = { name: NAMES[st], files, counts, regions: regionList, bytes };
}

const out = [
  "// GENERATED by tools/build-index.js. Do not edit by hand.",
  "// Manifest of per-state data files, lazy-loaded by lib/state-loader.js.",
  "window.STATE_INDEX = " + JSON.stringify(index, null, 1) + ";",
  "",
].join("\n");
fs.writeFileSync(path.join(STATES_DIR, "index.js"), out);
const tot = Object.values(index).reduce((a, s) => ({ p: a.p + s.counts.programs, r: a.r + s.counts.resources, s: a.s + s.counts.scholarships, g: a.g + (s.counts.guide ? 1 : 0) }), { p: 0, r: 0, s: 0, g: 0 });
console.log(`index.js written: ${Object.keys(index).length} states, ${tot.p} programs, ${tot.r} resources, ${tot.s} scholarships, ${tot.g} guides`);
