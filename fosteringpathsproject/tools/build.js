#!/usr/bin/env node
// Compiles the JSX sources listed in lib/jsx-files.js into dist/app.js with esbuild
// (plain React.createElement calls, no bundler, no minification so stack traces
// stay readable). Run after editing any .jsx file:  node tools/build.js
// Needs esbuild: npm i -D esbuild   (or set ESBUILD_MODULE to an installed copy).
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const esbuild = require(process.env.ESBUILD_MODULE || "esbuild");

const ROOT = path.resolve(__dirname, "..");
const list = fs.readFileSync(path.join(ROOT, "lib", "jsx-files.js"), "utf8");
const files = [...list.matchAll(/"([^"]+\.jsx)"/g)].map(m => m[1]);
if (!files.length) throw new Error("no JSX files found in lib/jsx-files.js");

const parts = [];
const hashes = {};
for (const f of files) {
  const src = fs.readFileSync(path.join(ROOT, f), "utf8");
  hashes[f] = crypto.createHash("sha1").update(src).digest("hex");
  const out = esbuild.transformSync(src, { loader: "jsx", target: "es2018", sourcefile: f, jsx: "transform" });
  parts.push(`// ---- ${f} ----\n${out.code}`);
}
fs.mkdirSync(path.join(ROOT, "dist"), { recursive: true });
const banner = `// GENERATED by tools/build.js from the JSX sources in lib/jsx-files.js. Do not edit; edit the .jsx files and rebuild.\n`;
fs.writeFileSync(path.join(ROOT, "dist", "app.js"), banner + parts.join("\n"));
fs.writeFileSync(path.join(ROOT, "dist", "build.json"), JSON.stringify({ built: new Date().toISOString(), files: hashes }, null, 1));
console.log(`dist/app.js written from ${files.length} files (${Math.round(fs.statSync(path.join(ROOT, "dist", "app.js")).size / 1024)} KB)`);
